// Bundle existing JPEG bytes into 4x4 geographic blocks. No resampling, new
// imagery, network download or changes to the original photographs/tiles.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packs = {};
const hash = createHash('sha256');
let totalBytes = 0;
for (const provider of ['google', 'esri']) {
  const text = await readFile(resolve(root, `src/services/${provider}TileCache.generated.ts`), 'utf8');
  const cache = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
  const folder = cache.cacheId || `esri-${cache.releaseId}`;
  const available = new Set(cache.tiles);
  const groups = new Set();
  for (const key of cache.tiles) {
    const [z, y, x] = key.split('/').map(Number);
    if (z >= 9) groups.add(`${z - 2}/${Math.floor(y / 4)}/${Math.floor(x / 4)}`);
  }
  packs[provider] = [];
  for (const group of [...groups].sort()) {
    const [z, y, x] = group.split('/').map(Number);
    const tiles = [], images = {}, chunks = [];
    let bytes = 0;
    for (let dy = 0; dy < 4; dy++) for (let dx = 0; dx < 4; dx++) {
      let sz = z + 2, sx = x * 4 + dx, sy = y * 4 + dy;
      while (sz >= 6 && !available.has(`${sz}/${sy}/${sx}`)) {
        sz--; sx = Math.floor(sx / 2); sy = Math.floor(sy / 2);
      }
      if (sz < 6) { tiles.push(null); continue; }
      const key = `${sz}/${sy}/${sx}`;
      if (!images[key]) {
        const data = await readFile(resolve(root, `public/map-tiles/${folder}/${key}.jpg`));
        images[key] = [bytes, data.length]; chunks.push(data); bytes += data.length;
      }
      tiles.push(key);
    }
    // Only publish complete geographic blocks. A normal tile provider remains
    // available outside the bundled area rather than inserting empty pixels.
    if (tiles.some(key => !key)) continue;
    const header = Buffer.from(JSON.stringify({ tiles, images }));
    const size = Buffer.alloc(4); size.writeUInt32LE(header.length);
    const data = Buffer.concat([size, header, ...chunks]);
    const output = resolve(root, `public/map-tiles/blocks-v1/${provider}/${group}.bin`);
    await mkdir(dirname(output), { recursive: true }); await writeFile(output, data);
    hash.update(data); totalBytes += data.length;
    packs[provider].push(group);
  }
  console.log(provider, packs[provider].length, 'blocks');
}
const revision = hash.digest('hex').slice(0, 16);
await writeFile(resolve(root, 'src/services/mapBlocks.generated.ts'),
  '// Generated by scripts/pack-map-tiles.mjs. Original imagery and credits are preserved.\n' +
  `export const MAP_BLOCKS = ${JSON.stringify({ revision, ...packs }, null, 2)} as const;\n`);
console.log((totalBytes / 1024 / 1024).toFixed(1), 'MiB; revision', revision);
